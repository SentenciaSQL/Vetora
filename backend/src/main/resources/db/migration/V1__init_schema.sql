-- Animalin multi-tenant SaaS schema (shared database, shared schema, tenant_id isolation)

CREATE TABLE plans (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)   NOT NULL UNIQUE,
    name_es             VARCHAR(120)  NOT NULL,
    name_en             VARCHAR(120)  NOT NULL,
    description_es      VARCHAR(500),
    description_en      VARCHAR(500),
    max_users           INT           NOT NULL DEFAULT 5,
    max_veterinarians   INT           NOT NULL DEFAULT 2,
    max_branches        INT           NOT NULL DEFAULT 1,
    max_storage_mb      INT           NOT NULL DEFAULT 1024,
    max_messages_month  INT           NOT NULL DEFAULT 200,
    reports_enabled     BOOLEAN       NOT NULL DEFAULT TRUE,
    messaging_enabled   BOOLEAN       NOT NULL DEFAULT TRUE,
    laboratory_enabled  BOOLEAN       NOT NULL DEFAULT FALSE,
    monthly_price       NUMERIC(10, 2) NOT NULL DEFAULT 0,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tenants (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                VARCHAR(80)   NOT NULL UNIQUE,
    name                VARCHAR(180)  NOT NULL,
    commercial_name     VARCHAR(180),
    logo_url            VARCHAR(500),
    dark_logo_url       VARCHAR(500),
    icon_url            VARCHAR(500),
    email               VARCHAR(180),
    phone               VARCHAR(40),
    address             VARCHAR(240),
    city                VARCHAR(120),
    country             VARCHAR(120),
    website             VARCHAR(240),
    instagram           VARCHAR(240),
    facebook            VARCHAR(240),
    timezone            VARCHAR(64)   NOT NULL DEFAULT 'Europe/Madrid',
    currency            VARCHAR(8)    NOT NULL DEFAULT 'EUR',
    default_locale      VARCHAR(8)    NOT NULL DEFAULT 'es',
    status              VARCHAR(20)   NOT NULL DEFAULT 'TRIAL',
    plan_id             BIGINT        REFERENCES plans (id),
    trial_ends_at       TIMESTAMP,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP,
    created_by          VARCHAR(120),
    updated_by          VARCHAR(120),
    deleted             BOOLEAN       NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMP
);

CREATE INDEX idx_tenants_status ON tenants (status);
CREATE INDEX idx_tenants_plan ON tenants (plan_id);

CREATE TABLE subscriptions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT        NOT NULL REFERENCES tenants (id),
    plan_id             BIGINT        NOT NULL REFERENCES plans (id),
    status              VARCHAR(20)   NOT NULL DEFAULT 'TRIAL',
    trial               BOOLEAN       NOT NULL DEFAULT TRUE,
    started_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    current_period_end  TIMESTAMP,
    cancelled_at        TIMESTAMP,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP
);

CREATE INDEX idx_subscriptions_tenant ON subscriptions (tenant_id, status);

CREATE TABLE tenant_settings (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT       NOT NULL UNIQUE REFERENCES tenants (id),
    date_format                 VARCHAR(32)  NOT NULL DEFAULT 'dd/MM/yyyy',
    default_appointment_min     INT          NOT NULL DEFAULT 30,
    cancellation_hours          INT          NOT NULL DEFAULT 12,
    notify_email                BOOLEAN      NOT NULL DEFAULT TRUE,
    notify_push                 BOOLEAN      NOT NULL DEFAULT TRUE,
    enabled_locales             VARCHAR(32)  NOT NULL DEFAULT 'es,en',
    updated_at                  TIMESTAMP,
    updated_by                  VARCHAR(120)
);

CREATE TABLE roles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL UNIQUE,
    name_es         VARCHAR(120) NOT NULL,
    name_en         VARCHAR(120) NOT NULL,
    description_es  VARCHAR(500),
    description_en  VARCHAR(500),
    system_role     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(80)  NOT NULL UNIQUE,
    name_es     VARCHAR(160) NOT NULL,
    name_en     VARCHAR(160) NOT NULL,
    module      VARCHAR(80)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles (id),
    permission_id BIGINT NOT NULL REFERENCES permissions (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(180) NOT NULL UNIQUE,
    password_hash   VARCHAR(120) NOT NULL,
    first_name      VARCHAR(80)  NOT NULL,
    last_name       VARCHAR(120) NOT NULL,
    phone           VARCHAR(40),
    document_id     VARCHAR(40),
    avatar_url      VARCHAR(500),
    locale          VARCHAR(8)   NOT NULL DEFAULT 'es',
    theme           VARCHAR(16)  NOT NULL DEFAULT 'system',
    email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at   TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP,
    created_by      VARCHAR(120),
    updated_by      VARCHAR(120),
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at      TIMESTAMP
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users (id),
    role_id BIGINT NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE tenant_memberships (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenants (id),
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    role_id     BIGINT      NOT NULL REFERENCES roles (id),
    branch_id   BIGINT,
    status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tenant_id, user_id)
);

CREATE INDEX idx_memberships_user ON tenant_memberships (user_id);
CREATE INDEX idx_memberships_tenant ON tenant_memberships (tenant_id, status);

CREATE TABLE refresh_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

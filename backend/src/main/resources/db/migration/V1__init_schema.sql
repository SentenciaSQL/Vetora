CREATE TABLE laboratory_results (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    pet_id           BIGINT       NOT NULL REFERENCES pets (id),
    veterinarian_id  BIGINT       REFERENCES veterinarians (id),
    consultation_id  BIGINT       REFERENCES consultations (id),
    name             VARCHAR(180) NOT NULL,
    lab_name         VARCHAR(160),
    collected_at     TIMESTAMP,
    result_summary   VARCHAR(4000),
    status           VARCHAR(30)  NOT NULL DEFAULT 'COMPLETED',
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(120),
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at       TIMESTAMP
);

CREATE TABLE stored_files (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       REFERENCES tenants (id),
    uploaded_by      BIGINT       REFERENCES users (id),
    file_name        VARCHAR(240) NOT NULL,
    content_type     VARCHAR(120),
    storage_key      VARCHAR(500) NOT NULL,
    size_bytes       BIGINT,
    category         VARCHAR(80),
    entity_type      VARCHAR(80),
    entity_id        BIGINT,
    public_file      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at       TIMESTAMP
);

CREATE INDEX idx_files_tenant_entity ON stored_files (tenant_id, entity_type, entity_id);

CREATE TABLE documents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    pet_id           BIGINT       REFERENCES pets (id),
    owner_id         BIGINT       REFERENCES owners (id),
    consultation_id  BIGINT       REFERENCES consultations (id),
    file_id          BIGINT       REFERENCES stored_files (id),
    uploaded_by      BIGINT       REFERENCES users (id),
    title            VARCHAR(240),
    category         VARCHAR(80),
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at       TIMESTAMP
);

CREATE INDEX idx_documents_tenant_pet ON documents (tenant_id, pet_id);

CREATE TABLE conversations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL REFERENCES tenants (id),
    owner_id    BIGINT       REFERENCES owners (id),
    pet_id      BIGINT       REFERENCES pets (id),
    subject     VARCHAR(240),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP
);

CREATE INDEX idx_conversations_tenant ON conversations (tenant_id, updated_at);

CREATE TABLE conversation_participants (
    conversation_id BIGINT NOT NULL REFERENCES conversations (id),
    user_id         BIGINT NOT NULL REFERENCES users (id),
    PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    conversation_id  BIGINT       NOT NULL REFERENCES conversations (id),
    sender_id        BIGINT       NOT NULL REFERENCES users (id),
    body             VARCHAR(4000),
    pet_id           BIGINT       REFERENCES pets (id),
    consultation_id  BIGINT       REFERENCES consultations (id),
    read_at          TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at       TIMESTAMP
);

CREATE INDEX idx_messages_conversation ON messages (conversation_id, created_at);

CREATE TABLE message_attachments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id   BIGINT       NOT NULL REFERENCES messages (id),
    file_id      BIGINT       REFERENCES stored_files (id),
    file_name    VARCHAR(240) NOT NULL,
    content_type VARCHAR(120),
    storage_key  VARCHAR(500) NOT NULL
);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       REFERENCES tenants (id),
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    type        VARCHAR(60)  NOT NULL,
    title_es    VARCHAR(180) NOT NULL,
    title_en    VARCHAR(180) NOT NULL,
    body_es     VARCHAR(500),
    body_en     VARCHAR(500),
    entity_type VARCHAR(80),
    entity_id   BIGINT,
    read_at     TIMESTAMP,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_user ON notifications (user_id, created_at);
CREATE INDEX idx_notifications_tenant ON notifications (tenant_id, created_at);

CREATE TABLE push_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    token       VARCHAR(512) NOT NULL,
    platform    VARCHAR(40),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, token)
);

CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT,
    user_id      BIGINT,
    username     VARCHAR(180),
    action       VARCHAR(80)  NOT NULL,
    entity_type  VARCHAR(80)  NOT NULL,
    entity_id    BIGINT,
    details      VARCHAR(2000),
    old_value    VARCHAR(2000),
    new_value    VARCHAR(2000),
    ip_address   VARCHAR(64),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_tenant ON audit_logs (tenant_id, created_at);
CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);

CREATE TABLE platform_settings (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_email           VARCHAR(180) NOT NULL DEFAULT 'soporte@animalin.app',
    default_locale          VARCHAR(8)   NOT NULL DEFAULT 'es',
    default_trial_days      INT          NOT NULL DEFAULT 14,
    maintenance_mode        BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_at              TIMESTAMP,
    updated_by              VARCHAR(120)
);

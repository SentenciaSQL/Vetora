SELECT owner.id, rp.permission_id
FROM roles owner
JOIN roles admin ON admin.code = 'TENANT_ADMIN'
JOIN role_permissions rp ON rp.role_id = admin.id
WHERE owner.code = 'TENANT_OWNER'
  AND NOT EXISTS (
        SELECT 1 FROM role_permissions existing
        WHERE existing.role_id = owner.id
          AND existing.permission_id = rp.permission_id
  );

